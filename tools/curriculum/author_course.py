def activity(activity_id, kind, prompt, answer, asset_id=None, withheld=False):
    item = {"id": activity_id, "kind": kind, "required": not withheld, "prompt": prompt, "answer": answer}
    if asset_id:
        item["assetId"] = asset_id
    if withheld:
        item["withheldFromPractice"] = True
    return item


def meaning_from_cue(prompt):
    """Turn the existing recall cue into an explanatory gloss, without inventing a translation."""
    text = prompt.split(". You may")[0].removeprefix("Write ").strip()
    return text[:1].upper() + text[1:].rstrip(".") + "."


