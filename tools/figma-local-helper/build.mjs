import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(dir, "../..");
const manifest = JSON.parse(fs.readFileSync(path.join(repo, "docs/product-specification/figma-build-manifest.json"), "utf8"));
const screens = JSON.parse(fs.readFileSync(path.join(dir, "screens.json"), "utf8"));
if (manifest.fileKey !== "B1A9qEN1B7I3NJKISX39Dx" || manifest.frames.length !== 149) throw new Error("Unexpected source manifest; review before rebuilding.");
if (screens.length !== 149 || new Set(screens.map(s => s.id)).size !== 149) throw new Error("Expected 149 unique screen definitions.");
const bundle = "// Generated by build.mjs. Edit routing.cjs or plugin.js, then rebuild.\n" +
  "const PROJECT = " + JSON.stringify({ fileKey: manifest.fileKey, pageId: manifest.page.id, frames: manifest.frames, screens }) + ";\n" +
  fs.readFileSync(path.join(dir, "routing.cjs"), "utf8") + "\n" +
  fs.readFileSync(path.join(dir, "plugin.js"), "utf8") + "\n" +
  fs.readFileSync(path.join(dir, "refinement.js"), "utf8");
fs.writeFileSync(path.join(dir, "code.js"), bundle);
console.log("Built dependency-free local plugin for 149 screen definitions.");
